export function getMessage(locale: Locale, key: string, params: MessageParams = {}): string {
  const catalog = messages[locale] ?? messages.en;
  const fallbackCatalog = messages.en;
  const entry = catalog[key] ?? fallbackCatalog[key];

  if (typeof entry === 'function') {
    return entry(params);
  }

  if (typeof entry === 'string') {
    return interpolate(entry, params);
  }

  return key;
}
